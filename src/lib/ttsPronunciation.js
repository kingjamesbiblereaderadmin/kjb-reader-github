// Built once at module load: word → respelling.
export const SPEECH_HINTS = (() => {
  const map = new Map();
  for (const line of HINT_TEXT.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const at = trimmed.indexOf('=');
    if (at < 1) continue;
    const word = trimmed.slice(0, at).trim().toLowerCase();
    const spoken = trimmed.slice(at + 1).trim();
    if (word && spoken) map.set(word, spoken);
  }
  return map;
})();

// Respells one word; returns it untouched when there is no hint.
export function respellForSpeech(word) {
  if (!word) return word;
  return SPEECH_HINTS.get(String(word).toLowerCase()) || word;
}

// Applies the hints to a whole passage. Whole words only, hyphenated names
// (`beer-sheba`) kept together as one lookup; possessives (`Baal's`) leave
// their `'s` in place after the stem is respelled.
export function applySpeechHints(text) {
  return String(text || '').replace(/[A-Za-z]+(?:-[A-Za-z]+)*/g, (word) => respellForSpeech(word));
}